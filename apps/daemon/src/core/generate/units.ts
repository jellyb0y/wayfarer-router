/**
 * The unit that loads the generated ruleset — at boot and during an apply, by the same path.
 *
 * **This did not exist, and its absence was invisible.** The ruleset was generated, written to
 * `/etc/wayfarer/nftables.conf`, shown in the plan review and compared by the differ — and nothing
 * ever ran `nft -f` on it. On a device that had applied a profile and then been power-cycled, the
 * kill-switch, the IPv6 rejection, the management-port rules and the time-sync bypass were all absent
 * while every file on disk said otherwise.
 *
 * The check that normally catches this class — `is-active` **and** `is-enabled` — starts from units,
 * and this fault was a *file that no unit consumed*. That is the general rule now recorded in
 * `docs/06-apply-and-rollback.md`: every generated artefact must name the unit that loads it.
 *
 * One mechanism for both paths, and that is the point rather than a convenience. The reconciler
 * restarts this unit instead of shelling out to `nft`, so the thing exercised during an apply is
 * exactly the thing that runs at boot. Two mechanisms would mean the boot path is tested only by
 * power-cycling, which nobody does on purpose.
 *
 * `ExecStartPre` validates first, so a malformed ruleset fails the unit instead of half-loading one.
 *
 * **No `ExecStop`, deliberately.** A distribution's own nftables unit flushes on stop; for us a
 * kill-switch that disappears when a unit is stopped is a leak. Our ruleset file already deletes and
 * recreates only our own table, so a restart is self-cleaning without ever flushing rules belonging to
 * anything else on the device.
 */
export function firewallUnit(
  options: { nftPath?: string; ipPath?: string; timePorts?: number[] } = {},
): DesiredUnit {
  const nft = options.nftPath ?? '/usr/sbin/nft';
  const ipPath = options.ipPath ?? '/usr/sbin/ip';
  const timePorts = options.timePorts ?? [123];

  /**
   * One policy rule, made idempotent. `ip rule add` is not: restarting this unit without the delete
   * loop stacks another copy every time, for ever.
   */
  const policyRule = (priority: number, selector: string): string =>
    `ExecStartPost=/bin/sh -c 'while ${ipPath} rule del priority ${priority} 2>/dev/null; do :; done; ` +
    `${ipPath} rule add priority ${priority} ${selector} lookup main'`;

  /**
   * **`iif lo` on every one of these, and it is not decoration.**
   *
   * A *forwarded* packet has no socket, so it has no owning user — and the kernel's uid selector matches
   * it anyway, as uid 0. Measured on the bench board, 2026-09-21: with a bare `uidrange 0-0` rule, a
   * client's packet resolved to `1.1.1.1 from 10.44.0.103 via 192.168.77.1 dev end0` — out of the tunnel
   * table entirely, onto the physical interface, carrying a client address nothing masquerades. Clients
   * could still resolve names, because a query to this device is local rather than forwarded, and could
   * reach nothing at all. "DNS works but nothing loads" for the second time in this project, from a
   * different cause.
   *
   * `iif lo` is how a policy rule says *locally originated*. With it, the same lookup returns
   * `via 172.19.0.2 dev tun0 table 2022` for the client and `via 192.168.77.1 dev end0` for the
   * device's own traffic — which is precisely the split these rules exist to make.
   *
   * The port rules carry it for the same reason and a second one: a client's own time query is forwarded
   * traffic and belongs in the tunnel like the rest of its traffic. Only *this device's* clock correction
   * needs to bypass.
   */
  const rules = [
    policyRule(DEVICE_MARK_RULE_PRIORITY, 'uidrange 0-0 iif lo'),
    ...timePorts.flatMap((port, index) => [
      policyRule(DEVICE_MARK_RULE_PRIORITY + 1 + index * 2, `ipproto udp dport ${port} iif lo`),
      policyRule(DEVICE_MARK_RULE_PRIORITY + 2 + index * 2, `ipproto tcp dport ${port} iif lo`),
    ]),
  ];
  return {
    name: 'wf-firewall.service',
    enabled: true,
    active: true,
    purpose: 'loads the generated firewall ruleset',
    content: [
      HEADER('Loads the generated nftables ruleset. Our table only; nothing else is flushed.'),
      '',
      '[Unit]',
      'Description=Wayfarer firewall ruleset',
      // Early, before anything can carry traffic. `DefaultDependencies=no` with an explicit
      // `After=sysinit.target` is the ordering a firewall needs: rules in place before the network
      // comes up, not after it has been up for a moment.
      'DefaultDependencies=no',
      'After=sysinit.target',
      'Before=network-pre.target',
      'Wants=network-pre.target',
      'Conflicts=shutdown.target',
      'Before=shutdown.target',
      '',
      '[Service]',
      'Type=oneshot',
      'RemainAfterExit=yes',
      // Validate, then load. `nft -c -f` catches a syntax error before a partial ruleset reaches the
      // kernel, and it names the line, which is why the unit fails with a message somebody can act on.
      `ExecStartPre=${nft} -c -f ${PATHS.firewall}`,
      `ExecStart=${nft} -f ${PATHS.firewall}`,
      //
      // **The rules that keep the device's own traffic out of the tunnel.**
      //
      // The ruleset above also *marks* that traffic, and marking alone does nothing: measured on the
      // bench board, 2026-09-21, with the mark being set and nothing consulting it, `ip route get
      // <address> mark 0x1e7` returned the tunnel device exactly as the unmarked lookup did, and the
      // tunnel client's own connection to its VPN server sat inside the proxy core. The protection was
      // written, documented, and inert — and because the traffic still arrived, through the core and out
      // its direct outbound, nothing looked wrong.
      //
      // **Why these select on uid and port rather than on that mark, which is the trap worth keeping.**
      // A policy rule matching the mark *was* tried first and broke the device's own networking outright.
      // The source address is chosen on the **first** route lookup, which happens before the output hook
      // runs and therefore before the mark exists: the packet was given `172.19.0.1`, the tunnel's own
      // address. Setting the mark then triggers a reroute, and the reroute keeps a source address that is
      // still local to the machine. The result was packets leaving the physical interface carrying an
      // address the upstream network cannot route a reply to — measured: every marked connection timed
      // out while the same connection bound explicitly to a real address succeeded, and `ping -I` worked
      // because binding to an interface skips the decision entirely. A mark cannot fix a source that was
      // already chosen.
      //
      // `uidrange` and `dport` are known at the first lookup, so the right table is consulted before a
      // source is picked and the address is correct by construction rather than by correction.
      //
      // Two selectors because one does not cover the other: root-owned traffic is the tunnel clients and
      // the core itself, and the time ports are there because **the time service does not run as root** —
      // a rule written only in terms of the user misses it entirely, and that failure is self-locking,
      // since correcting a wrong clock needs a time query and transports that authenticate on a timestamp
      // refuse to connect while the clock is wrong.
      //
      // They live here rather than in a unit of their own because the ruleset and these rules are one
      // protection: a separate unit is a second thing to forget to enable.
      //
      // **Why they win whatever the core does.** The core installs its own policy rules in the 9000-9010
      // range on start and removes them on stop. Linux evaluates policy rules in ascending priority order,
      // so these are consulted before all of them — whichever was installed first, and across any number
      // of core restarts. That is a property of the priority, not of the order things happened in.
      ...rules,
      '# No ExecStop: see the generator comment. Stopping this unit must not remove the rules, and',
      '# nothing here may flush a ruleset that other software has tables in.',
      '',
      '[Install]',
      'WantedBy=multi-user.target',
      '',
    ].join('\n'),
  };
}

/**
 * A marker the tunnel units order themselves after.
 *
 * Its whole purpose is the ordering rule that earned its place: the firewall must be in place before
 * anything that talks to the network starts, because the rule letting time synchronisation bypass the
 * tunnel has to exist before the first query goes out — and a wrong clock makes every
 * timestamp-authenticated transport fail while direct connections work normally.
 *
 * It now *requires* the unit that loads the ruleset rather than merely marking a moment. The
 * consequence is deliberate and is the right way round: when the firewall unit fails, this target is
 * not reached, the core and the access point do not start, and the device serves no clients with the
 * rules absent — while management stays reachable precisely because nothing loaded.
 */
export function firewallReadyTarget(): DesiredUnit {
  return {
    name: 'wf-firewall-ready.target',
    enabled: true,
    active: true,
    purpose: 'ordering marker: the generated ruleset is loaded',
    content: [
      HEADER('Reached once the generated firewall ruleset has been loaded.'),
      '',
      '[Unit]',
      'Description=Wayfarer firewall is in place',
      // Requires, not Wants: a target reached whether or not the ruleset loaded would let the units
      // ordered after it start with no rules in place, which is the leak this ordering exists to stop.
      'Requires=wf-firewall.service',
      'After=wf-firewall.service',
      'RefuseManualStart=no',
      '',
      '[Install]',
      'WantedBy=multi-user.target',
      '',
    ].join('\n'),
  };
}

/** Every template this project ships. Installed once; instances are enabled per profile. */
export function templateUnits(options: { upScript: string; nftPath?: string; wayPath?: string; timePorts?: number[] }): DesiredUnit[] {
  const wayPath = options.wayPath ?? '/usr/local/bin/way';
  return [
    firewallUnit({ ...(options.nftPath ? { nftPath: options.nftPath } : {}), ...(options.timePorts ? { timePorts: options.timePorts } : {}) }),
    firewallReadyTarget(),
    rederiveUnit({ wayPath }),
    routeCheckUnit({ wayPath }),
    hostapdUnit(),
    supplicantUnit(),
    dhcpUnit(),
    openvpnUnit({ upScript: options.upScript }),
    transportUnit(),
    socksUnit(),
  ];
}

/**
 * Templates whose instance name is an **interface name**, and which therefore derive a device unit
 * from it.
 *
 * Only these are subject to the no-hyphen rule. It is worth being precise about, because the rule is
 * usually stated as "generated names contain no hyphen" and that is narrower than it sounds: systemd
 * escaping `-` as `\x2d` only matters when a unit name is turned *back* into a device path. A tunnel
 * id may contain a hyphen — `wf-openvpn@t-hq.service` is a perfectly good unit — because nothing
 * in that template derives `sys-subsystem-net-devices-…` from the instance. Applying the interface
 * rule to tunnel ids would reject ids the profile schema allows, for a reason that does not exist.
 */
const INTERFACE_INSTANCED_TEMPLATES = new Set(['wf-hostapd@.service', 'wf-dhcp@.service']);

/** An instance name for a template. */
export function instanceOf(template: string, instance: string): string {
  const base = template.replace(/@\.service$/, '');
  if (INTERFACE_INSTANCED_TEMPLATES.has(template) && instance.includes('-')) {
    throw new Error(
      `cannot build the instance "${base}@${instance}": this template derives a device unit from its ` +
        'instance, and systemd escapes "-" as "\\x2d" in unit names, so the dependency would name a ' +
        'unit that does not exist and BindsTo= would stop the service immediately',
    );
  }
  return `${base}@${instance}.service`;
}
